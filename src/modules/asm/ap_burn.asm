; ap_burn.asm — код, который stress.sys подсовывает дополнительным ядрам (AP).
;
; Раньше эти же байты лежали в stress_module.c руками набранными опкодами
; (0xFA, 0x31, 0xC0, ...) с комментариями-смещениями: любая правка требовала
; пересчитывать переходы вручную. Теперь источник один — этот файл, а
; tools/bin2h.py превращает его в build/ap_burn.h для модуля.
;
; Ядро просыпается по SIPI в реальном режиме по адресу 0x8000, греет АЛУ и
; останавливается, когда ядро положит 1 в байт-флаг по адресу 0x8020.

[BITS 16]
org 0x8000

start:
    cli
    xor ax, ax
    mov ds, ax

burn_loop:
    cmp byte [0x8020], 0        ; флаг остановки от ядра
    jne halt_core
    add ax, 0x1337              ; нагрузка на АЛУ
    xor dx, ax
    rol dx, 3
    jmp burn_loop

halt_core:
    hlt
    jmp halt_core
