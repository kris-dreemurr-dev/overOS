#ifndef XHCI_H
#define XHCI_H
// xhci.h — драйвер контроллера USB 3.0 (xHCI). См. xhci.c и xhci-msc.c.
//
// Зачем он нужен: на машинах последних лет EHCI в чипсете уже нет, остался
// только xHCI, и без этого драйвера overOS на них просто не увидит флешку,
// с которой загрузилась. Какие контроллеры поднимать, решает usb.c.

#include <stdint.h>

// Инициализация контроллера: 0 — успех, <0 — ошибка
//  -1 контроллера нет на шине PCI
//  -2 регистры не отвечают (BAR не отображён)
//  -3 контроллер не сбросился
//  -4 не хватило памяти под кольца
int  xhci_init(void);

int  xhci_present(void);          // есть ли xHCI на шине (без инициализации)
int  xhci_port_count(void);       // сколько портов у контроллера
int  xhci_ports_connected(void);  // на скольких портах что-то воткнуто

// Подробный вывод драйвера на консоль (версия, порты, кольца). По умолчанию
// выключен: загрузочный экран оформлен как журнал systemd. Ошибки печатаются
// всегда, независимо от этого флага.
void xhci_set_verbose(int v);

// Сколько устройств удалось адресовать и есть ли среди них накопитель
int  xhci_device_count(void);
int  xhci_storage_found(void);

// Горячее подключение: пропавшие устройства снять, новые поднять (под usb_lock)
void xhci_poll(void);

#endif
