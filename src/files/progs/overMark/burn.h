#ifndef OVERMARK_BURN_H
#define OVERMARK_BURN_H
// burn.h — то, чем overMark греет процессор: «пушистый бублик», как у FurMark,
// только не на видеокарте, а на всех ядрах процессора. Тор с мехом трассируется
// лучами по функции расстояния (raymarching) — по четыре луча сразу на SSE.
// Фиксированное число шагов на луч, без раннего выхода: нагрузка ровная и
// предсказуемая, кадр от кадра не легчает.

#include <stdint.h>

typedef struct {
    float time;         // секунды с начала теста: вращение и шевеление меха
    int   steps;        // шагов на луч (нагрузка)
    int   ssaa;         // 1 — 4 подвыборки на пиксель (режим «экстрим»)
    int   w, h;         // размер кадра
    uint32_t* out;      // 0x00RRGGBB, w*h
} burn_frame_t;

// Строки [y0, y1) кадра. Чистая функция: можно звать с любого ядра одновременно
void burn_rows(const burn_frame_t* f, int y0, int y1);

#endif
