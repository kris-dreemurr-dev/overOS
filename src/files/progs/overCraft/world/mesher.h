#ifndef OVCRAFT_MESHER_H
#define OVCRAFT_MESHER_H
// =============================================================================
// mesher.h — сетка чанка для движка: только видимые грани.
//
// Грань блока рисуется, если сосед с её стороны её не закрывает (воздух,
// вода, листва, стекло). У каждой вершины своя яркость — затенение углов
// (ambient occlusion): чем больше блоков вокруг угла, тем он темнее. Это и
// даёт «объём» без настоящего освещения. Диагональ квадрата выбирается по
// яркости углов, иначе на гранях видны полосы.
//
// Перед построением блоки чанка с соседями копируются в рамку на клетку шире
// (MeshScratch): так соседа любой грани и угла можно взять без проверок
// границ. Работает на рабочих ядрах — память только из рамки и буферов
// секций, выделенных заранее.
// =============================================================================

#include "chunk.h"

struct MeshScratch {
    static const int PX = cfg::CHUNK + 2, PY = cfg::WORLD_H + 2;
    uint8_t pad[PX * PY * PX];
    static int at(int x, int y, int z) { return ((y + 1) * PX + (z + 1)) * PX + (x + 1); }
};

namespace mesher {

// nb[dz + 1][dx + 1] — соседи (центр — сам c). Строит грязные секции; если
// секции не хватило буфера, оставляет её грязной и пишет need_v/need_f.
void build(Chunk& c, const Chunk* const nb[3][3], MeshScratch& s);

} // namespace mesher

#endif
