#ifndef OVCRAFT_GENERATOR_H
#define OVCRAFT_GENERATOR_H
// =============================================================================
// generator.h — процедурный мир: рельеф, пляжи, снег на вершинах, пещеры,
// деревья. Всё выводится из координат и cfg::SEED, поэтому чанки можно
// считать в любом порядке и параллельно: соседние чанки сходятся по краю
// сами, без общения между собой (деревья на границе каждый чанк достраивает
// свою часть по тем же числам).
//
// fill() выполняется на рабочих ядрах: не выделяет память и не зовёт систему.
// =============================================================================

#include "chunk.h"

// Правка игрока: поверх сгенерированного мира, переживает выгрузку чанка
struct BlockEdit {
    int x, y, z;
    uint8_t block;
};

namespace gen {

int  surface_height(int wx, int wz);         // верхний твёрдый блок столба (без пещер)
void fill(Chunk& c, const BlockEdit* edits, int nedits);

} // namespace gen

#endif
